import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { authenticateUser } from "@/lib/auth";
import { checkPermission } from "@/lib/permissions";
import { createLivestockWithGeneratedTag } from "@/lib/livestockTag";

export async function GET(req) {
  try {
    const { user, error } = await authenticateUser(req);
    if (error) return error;

    if (!(await checkPermission(user, "dashboard", "livelihood", "READ"))) {
      return NextResponse.json({ error: "Forbidden: Insufficient permissions for livelihood" }, { status: 403 });
    }

    const { searchParams } = new URL(req.url);
    const healthStatus = searchParams.get("healthStatus");

    const where = {};
    if (healthStatus && healthStatus !== "All") where.healthStatus = healthStatus;

    const livestock = await prisma.livestock.findMany({
      where,
      include: {
        beneficiary: {
          select: { id: true, name: true }
        }
      },
      orderBy: { tagNumber: "asc" }
    });

    return NextResponse.json({ success: true, data: livestock });
  } catch (error) {
    console.error("Fetch livestock error:", error);
    return NextResponse.json({ error: "Internal Server Error" }, { status: 500 });
  }
}

export async function POST(req) {
  try {
    const { user, error } = await authenticateUser(req);
    if (error) return error;

    if (!(await checkPermission(user, "dashboard", "livelihood", "WRITE"))) {
      return NextResponse.json({ error: "Forbidden: Insufficient permissions for livelihood" }, { status: 403 });
    }

    if (user.role.name !== "ADMIN" && user.role.name !== "FELLOW") {
      return NextResponse.json({ error: "Forbidden: Admin or Fellow access only" }, { status: 403 });
    }

    const body = await req.json();
    const { beneficiaryId, tagNumber, animalType, breed, ageMonths, healthStatus } = body;

    if (!beneficiaryId || !animalType) {
      return NextResponse.json({ error: "Beneficiary ID and Animal Type are required" }, { status: 400 });
    }

    // Animal IDs are generated by the system and are guaranteed unique.
    const livestockItem = await createLivestockWithGeneratedTag(prisma, {
      beneficiaryId,
      tagNumber: tagNumber || null,
      animalType,
      breed,
      ageMonths: ageMonths ? parseInt(ageMonths) : null,
      healthStatus: healthStatus || "Healthy"
    });

    return NextResponse.json({ success: true, data: livestockItem }, { status: 201 });
  } catch (error) {
    console.error("Create livestock error:", error);
    return NextResponse.json({ error: "Internal Server Error" }, { status: 500 });
  }
}
